  native_ms INTEGER,
  native_body TEXT,
  workos_request TEXT,
  workos_status INTEGER,
  workos_ms INTEGER,
  workos_body TEXT,
  response_status INTEGER,
  error TEXT
);

CREATE INDEX IF NOT EXISTS idx_proxy_log_directory ON proxy_log (directory_id, id DESC);

