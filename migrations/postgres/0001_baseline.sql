-- Postgres baseline: the same logical schema as migrations/*.sql (the SQLite/D1
-- source of truth), squashed. There are no Postgres deployments older than this
-- file, so there is no history worth replaying — and 0007's DROP/INSERT/RENAME
-- table rebuild exists only because SQLite cannot alter a CHECK constraint.
--
-- From here on a schema change ships in BOTH sets in the same PR, and
-- tests/schema-parity.test.ts compares the two live schemas so a one-sided edit
-- fails CI rather than surfacing as a driver-specific bug.

-- Timestamps are TEXT holding SQLite's `YYYY-MM-DD HH:MM:SS`, and that exact
-- shape is load-bearing: the status endpoint folds the space to a T for its ETag,
-- ordering relies on the format being fixed-width and lexicographic, and the
-- panel renders the string as-is. So rather than rewrite 20 call sites' SQL (or
-- migrate the columns to timestamptz and change all three), Postgres gets the
-- function they already call. Only `datetime('now')` is implemented — anything
-- else raises instead of quietly returning the wrong instant.
CREATE OR REPLACE FUNCTION datetime(spec text) RETURNS text
  LANGUAGE plpgsql STABLE AS $fn$
BEGIN
  IF spec <> 'now' THEN
    RAISE EXCEPTION 'datetime(%) is not implemented by the scim-bridge Postgres driver; only datetime(''now'')', spec;
  END IF;
  RETURN to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS');
END
$fn$;

